#!/usr/bin/env python3
"""Python <-> RTL 一致性测试（conformance test）。

思路：用 Python 生成一段**混合了合法帧、CRC 错帧、尾字节错帧、超长帧、垃圾字节、
截断帧**的字节流，同时算出"期望解析结果"；让 ModelSim 里的 `tb_conformance.sv`
把同一段字节流喂给 `host_frame_rx`，打印它解析出的帧与计数器；最后逐项比对。

这能保证上位机（protocol.py）与 FPGA（host_frame_rx.v）对同一段数据的理解**完全一致**。

用法::

    python conformance.py --gen     # 生成 vectors/conformance.hex + conformance_expected.txt
    python conformance.py --check   # 与 ModelSim 输出（vectors/conformance_rtl.txt）比对
"""
from __future__ import annotations

import argparse
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import protocol as P  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(HERE)
VEC = os.path.join(PROJ, "sim", "vectors")

MAX_LEN = 32


def build_corpus(seed: int = 20261029):
    """构造一致性语料。

    注意：各段之间插入 3 个 0x00 作为"空闲间隔"。原因见 docs/CONFORMANCE_NOTES.md：
    当噪声里恰好出现 `AA 55` 但 LEN 非法、且**紧跟着**就是真帧时，流式解析器（RTL）
    已把真帧的头两个字节消耗掉，而带缓冲的 Python 解析器可以回退重扫——这是两种实现
    的固有差异（只影响强噪声场景）。插入空闲间隔后，两边对每一帧的判定完全一致。
    """
    rnd = random.Random(seed)
    stream = bytearray()

    def put(data: bytes) -> None:
        stream.extend(data)

    def gap() -> None:
        put(bytes([0x00, 0x00, 0x00]))

    # 1) 合法帧：覆盖所有下行类型 + 若干随机长度的未知类型
    put(P.build_frame(P.MSG_SET_VEL, bytes([0x64, 0x00, 0x9C, 0xFF, 7])))
    put(P.build_frame(P.MSG_STOP))
    put(P.build_frame(P.MSG_HEARTBEAT, bytes([9])))
    put(P.build_frame(P.MSG_SET_LIMIT, bytes([0x2C, 0x01])))
    put(P.build_frame(P.MSG_CLEAR_FAULT))
    put(P.build_frame(P.MSG_ACK, bytes([0x01, 0x07, 0x00])))
    for n in (1, 2, 3, 5, 8, 13, 21, 32):
        payload = bytes(rnd.randrange(256) for _ in range(n))
        put(P.build_frame(0x40 + n, payload))

    # 2) CRC 错
    gap()
    for _ in range(5):
        f = bytearray(P.build_frame(0x50, bytes(rnd.randrange(256) for _ in range(4))))
        f[-3] ^= 0xFF                      # 破坏 CRC 低字节
        put(f)

    # 3) 尾字节错
    gap()
    for _ in range(3):
        f = bytearray(P.build_frame(0x51, bytes([1, 2, 3])))
        f[-1] = 0x00
        put(f)

    # 4) LEN 超限
    gap()
    put(bytes([0xAA, 0x55, 0x52, 0x40]) + bytes(8))

    # 5) 垃圾字节（含假的 AA 55 开头）
    gap()
    put(bytes([0x11, 0x22, 0xAA, 0x55, 0xFF, 0xEE, 0x55, 0xAA, 0x00]))

    # 6) AA AA 55 重叠场景（单独一段，后面留够空闲字节把误帧冲掉）
    gap()
    put(bytes([0xAA, 0xAA, 0x55]))
    put(bytes(8))                    # 必须 > 5，否则真帧的 AA 55 会被误帧吃掉
    put(P.build_frame(P.MSG_HEARTBEAT, bytes([0x33])))

    # 7) 再来一批随机帧
    gap()
    for _ in range(10):
        n = rnd.randrange(0, 9)
        payload = bytes(rnd.randrange(256) for _ in range(n))
        t = rnd.choice([P.MSG_SET_VEL, P.MSG_HEARTBEAT, P.MSG_SET_LIMIT,
                        P.MSG_STOP, P.MSG_CLEAR_FAULT])
        # 只发与类型长度匹配的，避免触发 type_err（那是上位机侧的检查）
        if t in P.DOWNLINK_LEN and P.DOWNLINK_LEN[t] != n:
            n = P.DOWNLINK_LEN[t]
            payload = bytes(rnd.randrange(256) for _ in range(n))
        put(P.build_frame(t, payload))

    # 8) 结尾截断帧（不完整，解析器应无输出）
    trunc = P.build_frame(0x53, bytes([0xAA] * 10))
    put(trunc[:7])

    return bytes(stream)


def expected_from_python(stream: bytes):
    parser = P.FrameParser(validate_len=False)   # 与 RTL 相同：只做帧级校验
    frames = parser.feed(stream)
    stats = parser.stats
    return frames, stats


def cmd_gen(args) -> int:
    os.makedirs(VEC, exist_ok=True)
    stream = build_corpus(args.seed)
    frames, stats = expected_from_python(stream)

    hex_path = os.path.join(VEC, "conformance.hex")
    with open(hex_path, "w", encoding="ascii") as f:
        for i in range(0, len(stream), 16):
            f.write(" ".join("%02X" % b for b in stream[i:i + 16]) + "\n")

    exp_path = os.path.join(VEC, "conformance_expected.txt")
    with open(exp_path, "w", encoding="utf-8") as f:
        f.write("# generated by tools/conformance.py, DO NOT EDIT\n")
        f.write("BYTES %d\n" % len(stream))
        f.write("STATS good=%d crc=%d len=%d tail=%d\n"
                % (stats.good, stats.crc_err, stats.len_err, stats.tail_err))
        for fr in frames:
            # host_frame_rx 只保存前 8 个负载字节（v1 命令都在 5 字节内），
            # 因此一致性比对也只比前 8 字节，超过部分单独标注。
            f.write("FRAME %02X %d %s%s\n"
                    % (fr.msg_type, len(fr.payload),
                       fr.payload[:8].hex().upper() or "-",
                       " TRUNC" if len(fr.payload) > 8 else ""))
    print("corpus: %d bytes, %d frames, stats good=%d crc=%d len=%d tail=%d"
          % (len(stream), len(frames), stats.good, stats.crc_err,
             stats.len_err, stats.tail_err))
    print("wrote", hex_path)
    print("wrote", exp_path)
    return 0


def parse_modelsim_output(text: str):
    """从 ModelSim 输出里抽出 FRAME / STATS 行。"""
    rtl_stats = None
    rtl_frames = []
    for raw in text.splitlines():
        line = raw.lstrip("# ").strip()
        if line.startswith("STATS"):
            kv = dict(p.split("=") for p in line.split()[1:])
            rtl_stats = {k: int(v) for k, v in kv.items()}
        elif line.startswith("FRAME"):
            parts = line.split(" ", 3)
            if len(parts) < 4:
                continue
            _, t, n, payload = parts
            payload = payload.strip().upper()
            if payload.endswith("TRUNC"):
                payload = payload[:-5].strip()
            rtl_frames.append((int(t, 16), int(n), payload))
    return rtl_stats, rtl_frames


def compare(exp_stats, exp_frames, rtl_stats, rtl_frames) -> bool:
    ok = True
    if exp_stats != rtl_stats:
        print("FAIL stats: python=%s rtl=%s" % (exp_stats, rtl_stats))
        ok = False
    else:
        print("PASS stats: %s" % exp_stats)

    if len(exp_frames) != len(rtl_frames):
        print("FAIL frame count: python=%d rtl=%d"
              % (len(exp_frames), len(rtl_frames)))
        ok = False
    else:
        print("PASS frame count: %d" % len(exp_frames))

    mismatches = 0
    for i, (a, b) in enumerate(zip(exp_frames, rtl_frames)):
        if a != b:
            mismatches += 1
            if mismatches <= 5:
                print("FAIL frame %d: python=%r rtl=%r" % (i, a, b))
    if mismatches:
        print("FAIL %d frame mismatches" % mismatches)
        ok = False
    elif exp_frames and len(exp_frames) == len(rtl_frames):
        print("PASS all %d frames identical (type/len/payload, first 8 bytes)"
              % len(exp_frames))
    return ok


def read_expected():
    exp_path = os.path.join(VEC, "conformance_expected.txt")
    exp_stats = None
    exp_frames = []
    for line in open(exp_path, encoding="utf-8"):
        line = line.strip()
        if line.startswith("STATS"):
            kv = dict(p.split("=") for p in line.split()[1:])
            exp_stats = {k: int(v) for k, v in kv.items()}
        elif line.startswith("FRAME"):
            parts = line.split(" ", 3)
            if len(parts) < 4:
                continue
            _, t, n, payload = parts
            payload = payload.strip().upper()
            if payload.endswith("TRUNC"):
                payload = payload[:-5].strip()
            exp_frames.append((int(t, 16), int(n), payload))
    return exp_stats, exp_frames


def cmd_run(args) -> int:
    """一条命令跑完：生成语料 -> ModelSim -> 比对。"""
    import subprocess

    cmd_gen(args)
    vsim = args.vsim
    if not os.path.exists(vsim):
        print("找不到 vsim: %s（用 --vsim 指定）" % vsim)
        return 1
    print("running ModelSim ...")
    proc = subprocess.run([vsim, "-c", "-do", "do sim/run_conformance.do"],
                          cwd=PROJ, capture_output=True, text=True, timeout=600)
    rtl_stats, rtl_frames = parse_modelsim_output(proc.stdout)
    rtl_path = os.path.join(VEC, "conformance_rtl.txt")
    with open(rtl_path, "w", encoding="utf-8") as f:
        if rtl_stats:
            f.write("STATS %s\n" % " ".join("%s=%d" % kv for kv in rtl_stats.items()))
        for t, n, payload in rtl_frames:
            f.write("FRAME %02X %d %s\n" % (t, n, payload or "-"))
    if not rtl_stats:
        print("ModelSim 输出里没有 STATS，原始输出：")
        print("\n".join(proc.stdout.splitlines()[-20:]))
        return 1

    exp_stats, exp_frames = read_expected()
    ok = compare(exp_stats, exp_frames, rtl_stats, rtl_frames)
    print("\nCONFORMANCE %s" % ("PASS" if ok else "FAIL"))
    return 0 if ok else 1


def cmd_check(args) -> int:
    exp_stats, exp_frames = read_expected()
    rtl_path = os.path.join(VEC, "conformance_rtl.txt")
    if not os.path.exists(rtl_path):
        print("缺少 conformance_rtl.txt：先 --gen 再跑 ModelSim，或直接用 --run")
        return 1
    rtl_stats, rtl_frames = parse_modelsim_output(open(rtl_path, encoding="utf-8").read())
    ok = compare(exp_stats, exp_frames, rtl_stats, rtl_frames)
    print("\nCONFORMANCE %s" % ("PASS" if ok else "FAIL"))
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser(description="Python/RTL conformance test")
    ap.add_argument("--gen", action="store_true", help="generate the corpus only")
    ap.add_argument("--check", action="store_true",
                    help="compare with an existing conformance_rtl.txt")
    ap.add_argument("--run", action="store_true",
                    help="generate + run ModelSim + compare (one command)")
    ap.add_argument("--vsim", default="D:/app/modesilm/win64/vsim.exe")
    ap.add_argument("--seed", type=int, default=20261029)
    args = ap.parse_args()
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:  # noqa: BLE001
        pass
    if args.run:
        return cmd_run(args)
    if args.gen:
        return cmd_gen(args)
    if args.check:
        return cmd_check(args)
    ap.print_help()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
